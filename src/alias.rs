/// The venue's own base for a unified base; None when the venue's same-name market is a different asset.
pub fn venue_base(ex: Exchange, market: Market, base: &str) -> Option<String> {
    if market != Market::Perp { return Some(base.to_string()); }
    match PERP.iter().find(|(b, e, _)| *e == ex && b.eq_ignore_ascii_case(base)) {
        Some((_, _, n)) => n.map(str::to_string),
        None => Some(base.to_string()),
    }
}

/// The unified base for a venue's own perp base (e.g. Hyperliquid "xyz:GOLD" -> "XAU").
pub fn unified_base(ex: Exchange, native: &str) -> String {
    PERP.iter().find(|(_, e, n)| *e == ex && n.is_some_and(|n| n.eq_ignore_ascii_case(native))).map_or_else(|| native.to_string(), |(b, _, _)| b.to_string())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn round_trip() {
        for (b, e, n) in PERP {
            assert_eq!(venue_base(*e, Market::Perp, b).as_deref(), *n);
            if let Some(n) = n { assert_eq!(unified_base(*e, n), *b); }
        }
        assert_eq!(venue_base(Exchange::Binance, Market::Perp, "BTC").as_deref(), Some("BTC"));
        assert_eq!(venue_base(Exchange::Hyperliquid, Market::Spot, "XAU").as_deref(), Some("XAU"));
    }
}
